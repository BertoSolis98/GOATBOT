// Generates src/avatar/shapes.gen.ts: GoatBot's own bot silhouettes, drawn from math
// (polar curves and superellipses), so the project ships no third-party artwork.
// Each shape is one body outline plus two eye holes (evenodd); BotAvatar paints the
// outline white underneath so the eyes read as white on any background.
//
//   node web/scripts/gen-shapes.mjs
import fs from 'node:fs';
import path from 'node:path';

const VB = 55.2;           // viewBox size, matches BotAvatar's OVERDRAW (55.2 / 36)
const C = VB / 2;          // center
const FIT = 33.1;          // the body fits in a FIT x FIT box
const STEPS = 240;

const TAU = Math.PI * 2;
const sgn = (v) => (v < 0 ? -1 : 1);
const pw = (v, e) => sgn(v) * Math.abs(v) ** e;

// Each shape returns points for t in [0, 1).
const polar = (r) => (t) => { const a = t * TAU - Math.PI / 2; const k = r(a); return [k * Math.cos(a), k * Math.sin(a)]; };
const superellipse = (w, h, n) => (t) => { const a = t * TAU; return [w * pw(Math.cos(a), 2 / n), h * pw(Math.sin(a), 2 / n)]; };
const roundedPolygon = (sides, roundness = 0.18, rot = -Math.PI / 2) => polar((a) => {
  // Distance to a regular polygon's edge, blended toward a circle to soften corners.
  const seg = TAU / sides;
  const local = ((((a - rot) % seg) + seg) % seg) - seg / 2;
  const edge = Math.cos(Math.PI / sides) / Math.cos(local);
  return edge * (1 - roundness) + roundness;
});

const SHAPES = {
  blob: polar(() => 1),
  pebble: polar((a) => 1 + 0.06 * Math.sin(2 * a + 0.6) + 0.04 * Math.cos(3 * a)),
  egg: (t) => { const a = t * TAU; const y = Math.sin(a); return [Math.cos(a) * 0.82 * (1 + 0.12 * y), y]; },
  square: superellipse(1, 1, 4.5),
  tablet: superellipse(0.68, 1, 4),
  hex: roundedPolygon(6, 0.14, 0),
  house: roundedPolygon(5, 0.16),
  wedge: roundedPolygon(3, 0.1),
  star: polar((a) => 0.72 + 0.28 * Math.cos(5 * (a + Math.PI / 2))),
  sparkle: polar((a) => 0.5 + 0.5 * Math.abs(Math.cos(2 * (a + Math.PI / 2))) ** 3),
  flower: polar((a) => 0.7 + 0.3 * Math.abs(Math.cos(3 * a)) ** 0.5),
  clover: polar((a) => 0.62 + 0.38 * Math.abs(Math.cos(2 * a + Math.PI / 4)) ** 0.45),
  cloud: polar((a) => 0.86 + 0.14 * Math.abs(Math.sin(3.5 * (a + Math.PI / 2)))),
  heart: (t) => {
    const a = t * TAU;
    const x = 16 * Math.sin(a) ** 3;
    const y = -(13 * Math.cos(a) - 5 * Math.cos(2 * a) - 2 * Math.cos(3 * a) - Math.cos(4 * a));
    return [x, y];
  },
  teardrop: (t) => {
    const a = t * TAU;
    return [Math.sin(a) * Math.sin(a / 2) ** 1.6, -Math.cos(a)];
  },
};

const r2 = (v) => Math.round(v * 100) / 100;

function outline(fn) {
  const pts = Array.from({ length: STEPS }, (_, i) => fn(i / STEPS));
  const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
  const [x0, x1, y0, y1] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const s = FIT / Math.max(x1 - x0, y1 - y0);
  const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2;
  const mapped = pts.map(([x, y]) => [r2(C + (x - cx) * s), r2(C + (y - cy) * s)]);
  return 'M' + mapped.map(([x, y]) => `${x} ${y}`).join(' L') + 'Z';
}

function eye(cx, cy, rx = 1.55, ry = 2.5) {
  return `M${r2(cx + rx)} ${r2(cy)}A${rx} ${ry} 0 1 0 ${r2(cx - rx)} ${r2(cy)}A${rx} ${ry} 0 1 0 ${r2(cx + rx)} ${r2(cy)}Z`;
}

const EYES = eye(C - 4.2, C - 0.6) + eye(C + 4.2, C - 0.6);

const out = {};
for (const [name, fn] of Object.entries(SHAPES)) {
  const body = outline(fn);
  out[name] = { viewBox: `0 0 ${VB} ${VB}`, d: body + EYES, outline: body };
}

const file = `// AUTO-GENERATED by scripts/gen-shapes.mjs. Do not edit.\nexport interface ShapeDef { viewBox: string; d: string; outline: string }\nexport const SHAPES: Record<string, ShapeDef> = ${JSON.stringify(out)};\n`;
fs.writeFileSync(path.resolve(import.meta.dirname, '../src/avatar/shapes.gen.ts'), file);
console.log('shapes:', Object.keys(out).join(', '), (file.length / 1024).toFixed(1) + 'KB');
